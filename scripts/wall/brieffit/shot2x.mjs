import fs from 'node:fs';
const list = await (await fetch('http://127.0.0.1:47333/json')).json();
const pg = list.find(t => t.type === 'page' && /wall|18099|8099/.test(t.url)) || list.find(t => t.type === 'page');
const ws = new WebSocket(pg.webSocketDebuggerUrl);
let id = 0; const pend = {};
const send = (method, params = {}) => new Promise(r => { const i = ++id; pend[i] = r; ws.send(JSON.stringify({ id: i, method, params })); });
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend[m.id]) { pend[m.id](m); delete pend[m.id]; } };
await new Promise(r => ws.onopen = r);
const r = await send('Page.captureScreenshot', { format: 'jpeg', quality: 88, clip: { x: 0, y: 0, width: 1920, height: 1080, scale: 2 } });
fs.writeFileSync(process.argv[2], Buffer.from(r.result.data, 'base64'));
ws.close();
