-- 3. RoofGuard: store incoming calls and call-backs next to the outbound ones
-- direction: outbound (the dialer, as before) | inbound (someone called RoofGuard's line) | callback (Ava called them back after Jared's tap).
-- Every outbound-only report (KPIs, dial cap, opener scores) filters direction = 'outbound'.
