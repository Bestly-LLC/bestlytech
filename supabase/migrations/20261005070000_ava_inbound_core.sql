-- 1. Vault allowlists: the RoofGuard init-webhook secret
create or replace function public.ava_secret(p_name text)
returns text language plpgsql stable security definer set search_path = public, vault as $$
begin
  if p_name not in ('elevenlabs_api_key', 'telnyx_api_key', 'ava_webhook_secret', 'ava_sip_password', 'ava_init_secret', 'rg_init_secret') then
    raise exception 'ava_secret: % is not an Ava secret', p_name;
  end if;
  return (select decrypted_secret from vault.decrypted_secrets where name = p_name limit 1);
end $$;
create or replace function public.ava_secret_put(p_name text, p_value text)
returns void language plpgsql security definer set search_path = public, vault as $$
declare v_id uuid;
begin
  if p_name not in ('ava_webhook_secret', 'ava_sip_password', 'ava_init_secret', 'rg_init_secret') then raise exception 'ava_secret_put: % not allowed', p_name; end if;
  select id into v_id from vault.secrets where name = p_name;
  if v_id is null then perform vault.create_secret(p_value, p_name, 'Ava assistant: generated by setup');
  else perform vault.update_secret(v_id, p_value); end if;
end $$;
create or replace function public.rg_secret(p_name text)
returns text language plpgsql stable security definer set search_path = public, vault as $$
begin
  if p_name not in ('elevenlabs_api_key', 'elevenlabs_webhook_secret', 'telnyx_api_key', 'telnyx_sip_password', 'rg_init_secret') then
    raise exception 'rg_secret: % is not a RoofGuard secret', p_name;
  end if;
  return (select decrypted_secret from vault.decrypted_secrets where name = p_name limit 1);
end $$;
create or replace function public.rg_secret_put(p_name text, p_value text)
returns void language plpgsql security definer set search_path = public, vault as $$
