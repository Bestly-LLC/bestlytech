-- The placeholder lead every unknown incoming caller attaches to (rg_calls.lead_id is required). No phone and marked
-- do-not-call, so the dialer can never queue it; excluded from every outbound report.
with ins as (
  insert into public.rg_leads (company, state, timezone, risk_tier, contacts, category, pitch, pitch_source, enrich_status, line_type, dnc, priority, notes)
  select 'Inbound caller (unknown)', 'CA', 'America/Los_Angeles', 'LOW', '[]'::jsonb, 'generic', '', 'category', 'not_found', 'unknown', true, 0,
         'Placeholder for calls to RoofGuard''s line from numbers that are not a known lead. Never dialed by the queue.'
  where not exists (select 1 from public.rg_leads where state = 'CA' and company = 'Inbound caller (unknown)')
  returning id)
update public.rg_settings set inbound_lead_id = coalesce((select id from ins), (select id from public.rg_leads where state = 'CA' and company = 'Inbound caller (unknown)'))
 where id and inbound_lead_id is null;

-- 4. Follow-up calls (both lines). Proposed by Ava when a caller wants a call back; dialed only after Jared taps.
create table if not exists public.ava_followups (
  id uuid primary key default gen_random_uuid(),
  source text not null check (source in ('ava', 'roofguard')),
  call_id uuid,                                  -- the call that asked for it (ava_calls.id or rg_calls.id)
  phone text not null,
  name text,
  reason text,
  due_at timestamptz,                            -- when it goes out (empty while proposed)
  status text not null default 'proposed' check (status in ('proposed', 'approved', 'dialing', 'done', 'dismissed')),
  result_call_id uuid,
  note text,
  reminded_at timestamptz,
  dialed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source, call_id)
);
create index if not exists ava_followups_open on public.ava_followups (source, status, due_at);
alter table public.ava_followups enable row level security;
create policy "admin ava_followups" on public.ava_followups for all to authenticated
  using (public.has_role(auth.uid(), 'admin')) with check (public.has_role(auth.uid(), 'admin'));
grant select, update on public.ava_followups to authenticated;

create or replace function public.ava_calls_followup_trg() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.direction = 'inbound' and new.callback_wanted and coalesce(new.callback_number, new.phone) is not null then
    insert into ava_followups (source, call_id, phone, name, reason)
    values ('ava', new.id, coalesce(new.callback_number, new.phone), new.caller_name,
            left(coalesce(new.message, new.summary, 'Asked for a call back'), 300))
    on conflict (source, call_id) do nothing;
  end if;
  return new;
end $$;
create trigger ava_calls_followup after insert or update of callback_wanted on public.ava_calls
  for each row execute function public.ava_calls_followup_trg();

create or replace function public.rg_calls_inbound_followup_trg() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.direction = 'inbound' and new.callback_wanted and coalesce(new.callback_number, new.to_number) is not null then
    insert into ava_followups (source, call_id, phone, name, reason)
    values ('roofguard', new.id, coalesce(new.callback_number, new.to_number), new.caller_name,
            left(coalesce(new.message, new.summary, 'Asked for a call back'), 300))
    on conflict (source, call_id) do nothing;
  end if;
  return new;
end $$;
create trigger rg_calls_inbound_followup after insert or update of callback_wanted on public.rg_calls
  for each row execute function public.rg_calls_inbound_followup_trg();

