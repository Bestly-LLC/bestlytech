  topic text not null,
  fact text not null,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create index if not exists ava_knowledge_scope on public.ava_knowledge (scope, active);
alter table public.ava_knowledge enable row level security;
create policy "admin ava_knowledge" on public.ava_knowledge for all to authenticated
  using (public.has_role(auth.uid(), 'admin')) with check (public.has_role(auth.uid(), 'admin'));
